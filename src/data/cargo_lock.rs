//! Cargo.lock read as data: the packages and their checksums, which `cargo metadata` does not
//! report, and the fallback when `cargo metadata` fails (`cargo_lock_raw`, requirement R-VR-2).

use semver::Version;
use serde::Deserialize;

/// The packages that a Cargo.lock locks.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CargoLock {
    /// The packages, in the order of the file.
    pub packages: Box<[LockedPackage]>,
}

/// One `[[package]]` of a Cargo.lock.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct LockedPackage {
    /// The package name.
    pub name: Box<str>,
    /// The version.
    #[serde(deserialize_with = "super::deserialize_version")]
    pub version: Version,
    /// Where it comes from, as `registry+https://github.com/rust-lang/crates.io-index`. `None` for
    /// a path dependency and a workspace member.
    #[serde(default)]
    pub source: Option<Box<str>>,
    /// The SHA-256 of the `.crate` file, for a registry package. Cargo.lock version 1, which kept
    /// the checksums in a table of their own, has none here.
    #[serde(default)]
    pub checksum: Option<Box<str>>,
    /// The packages it depends on, as `name`, `name version` or `name version (source)`: only as
    /// much as tells them apart in the file.
    #[serde(default)]
    pub dependencies: Box<[Box<str>]>,
}

/// The parts of the file that are read.
#[derive(Deserialize)]
struct File {
    #[serde(default)]
    package: Box<[LockedPackage]>,
}

impl CargoLock {
    /// Reads the text of a Cargo.lock.
    ///
    /// # Errors
    ///
    /// Returns an error when the text is not TOML in the form of a Cargo.lock.
    pub fn parse(text: &str) -> Result<Self, toml::de::Error> {
        let file: File = toml::from_str(text)?;
        Ok(Self {
            packages: file.package,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packages_are_read_with_their_checksums() {
        let lock = CargoLock::parse(
            r#"
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde",
 "zstd-sys 2.0.16+zstd.1.5.7 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "serde"
version = "1.0.229"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0123"
"#,
        )
        .expect("a Cargo.lock");
        let [app, serde] = &*lock.packages else {
            panic!("two packages: {lock:?}");
        };
        assert_eq!(&*app.name, "app");
        assert_eq!(app.source, None);
        assert_eq!(app.dependencies.len(), 2);
        assert_eq!(serde.version, Version::new(1, 0, 229));
        assert_eq!(serde.checksum.as_deref(), Some("0123"));
    }

    #[test]
    fn an_invalid_version_is_an_error() {
        CargoLock::parse("[[package]]\nname = \"a\"\nversion = \"one\"\n")
            .expect_err("not a version");
    }
}
